/** 供应商 logo 徽标。 */
export function ProviderLogo({
  provider,
  size = 22,
  radius,
  style,
}: {
  provider: string;
  size?: number;
  radius?: number;
  style?: CSSProperties;
}) {
  const mark = MARKS[provider];
  const box: CSSProperties = {
    width: size,
    height: size,
    flex: `0 0 ${size}px`,
    borderRadius: radius ?? Math.round(size * 0.3),
    display: "grid",
    placeItems: "center",
    overflow: "hidden",
    position: "relative",
    ...style,
  };
  if (!mark) {
    // 未知供应商：中性底 + 首字母
    return (
      <span
        style={{
          ...box,
          background: "linear-gradient(150deg, #8e8e93, #636366)",
          color: "#fff",
          fontSize: Math.round(size * 0.42),
          fontWeight: 700,
        }}
      >
        {(provider[0] ?? "?").toUpperCase()}
      </span>
    );
  }
  return (
    <span style={{ ...box, background: mark.bg }}>
      {mark.d.length > 0 ? (
        <svg
          width={Math.round(size * 0.68)}
          height={Math.round(size * 0.68)}
          viewBox="0 0 24 24"
          fill="#fff"
          aria-hidden="true"
        >
          {mark.d.map((d, i) => (
            <path key={i} d={d} />
          ))}
        </svg>
      ) : (
        <span
          style={{
            color: "#fff",
            fontSize: Math.round(size * ((mark.letter ?? "").length > 2 ? 0.3 : 0.42)),
            fontWeight: 700,
            letterSpacing: "-0.02em",
          }}
        >
          {mark.letter}
        </span>
      )}
      {mark.badge ? (
        <span
          style={{
            position: "absolute",
            right: -1,
            bottom: -1,
            minWidth: Math.round(size * 0.44),
            height: Math.round(size * 0.44),
            borderRadius: Math.round(size * 0.22),
            background: "#fff",
            color: "#c2410c",
            fontSize: Math.round(size * 0.3),
            fontWeight: 700,
            display: "grid",
            placeItems: "center",
            lineHeight: 1,
            boxShadow: "0 0 0 1.5px rgba(0,0,0,0.06)",
          }}
        >
          {mark.badge}
        </span>
      ) : null}
    </span>
  );
}
